-- =============================================================================
-- USUN Rome Demo | 99_teardown.sql
-- Drops all demo objects in reverse dependency order, then the database,
-- warehouse, and role.
-- =============================================================================

USE ROLE DOS_ROME_DEMO_ROLE;
USE WAREHOUSE DOS_ROME_DEMO_WH;
USE DATABASE DOS_ROME_DEMO;

-- GOLD objects (depend on SILVER and BRONZE)
DROP AGENT IF EXISTS DOS_ROME_DEMO.GOLD.DOS_ROME_AGENT;
DROP STREAMLIT IF EXISTS DOS_ROME_DEMO.GOLD.DOS_ROME_DASHBOARD;
DROP SEMANTIC VIEW IF EXISTS DOS_ROME_DEMO.GOLD.DOS_ROME_SV;
DROP STAGE IF EXISTS DOS_ROME_DEMO.GOLD.STREAMLIT_STAGE;

-- SILVER objects
DROP CORTEX SEARCH SERVICE IF EXISTS DOS_ROME_DEMO.SILVER.POLICY_DOCS_SEARCH;
DROP CORTEX SEARCH SERVICE IF EXISTS DOS_ROME_DEMO.SILVER.SECTOR_INTEL_SEARCH;

-- BRONZE objects
DROP TABLE IF EXISTS DOS_ROME_DEMO.BRONZE.CRM_ACTIVITY_LOG;
DROP TABLE IF EXISTS DOS_ROME_DEMO.BRONZE.SECTOR_INTELLIGENCE;
DROP TABLE IF EXISTS DOS_ROME_DEMO.BRONZE.SUMMIT_ATTENDEES;
DROP TABLE IF EXISTS DOS_ROME_DEMO.BRONZE.MISSION_PRIORITIES;
DROP TABLE IF EXISTS DOS_ROME_DEMO.BRONZE.POLICY_DOCUMENTS;
DROP TABLE IF EXISTS DOS_ROME_DEMO.BRONZE.CRM_CONTACTS;

-- Schemas
DROP SCHEMA IF EXISTS DOS_ROME_DEMO.GOLD;
DROP SCHEMA IF EXISTS DOS_ROME_DEMO.SILVER;
DROP SCHEMA IF EXISTS DOS_ROME_DEMO.BRONZE;

-- Database, warehouse, role
USE ROLE ACCOUNTADMIN;
DROP DATABASE IF EXISTS DOS_ROME_DEMO;
DROP WAREHOUSE IF EXISTS DOS_ROME_DEMO_WH;
DROP ROLE IF EXISTS DOS_ROME_DEMO_ROLE;
